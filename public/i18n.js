export function normalizeLang(value) {
  return value === "sv" ? "sv" : "en";
}

export function langFromUrl() {
  return normalizeLang(new URLSearchParams(location.search).get("lang"));
}

export function t(lang, key, vars = {}) {
  let text = strings[normalizeLang(lang)]?.[key] || strings.en[key] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function withLang(url, lang) {
  const parsed = new URL(url, location.origin);
  parsed.searchParams.set("lang", normalizeLang(lang));
  return parsed.toString();
}

export function applyI18n(lang, root = document) {
  const code = normalizeLang(lang);
  document.documentElement.lang = code;
  if (strings[code].hostTitle && document.title) {
    /* titles set by callers */
  }
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.textContent = t(code, el.dataset.i18n);
  }
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
    el.setAttribute("placeholder", t(code, el.dataset.i18nPlaceholder));
  }
  for (const el of root.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(code, el.dataset.i18nAria));
  }
  for (const el of root.querySelectorAll("[data-spark-key]")) {
    el.dataset.spark = t(code, el.dataset.sparkKey);
  }
}
